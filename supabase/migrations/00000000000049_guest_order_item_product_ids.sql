-- Gifto Marketplace - UX Batch 1: expose the product id on guest order items.
--
-- Reorder from the guest order page needs to know which products were
-- ordered, and the historical names alone cannot identify them. This
-- adds `product_id` to each item in `get_guest_order`'s JSON shape;
-- nothing else changes (migration 48's gift fields stay, same auth
-- checks, same service_role-only grants). The product id is not
-- sensitive: it is already visible on every public product page.
--
-- Rollback: re-run migration 48's `get_guest_order` definition to drop
-- the key again.

create or replace function public.get_guest_order(
  p_order_id uuid,
  p_token_hash text
)
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select jsonb_build_object(
    'id', o.id,
    'reference', o.public_reference,
    'status', o.status,
    'currency', o.currency,
    'subtotal_minor', o.subtotal_minor,
    'delivery_fee_minor', o.delivery_fee_minor,
    'total_minor', o.total_minor,
    'recipient_name', o.recipient_name,
    'contact_phone', o.contact_phone,
    'address_line', o.address_line,
    'city', o.city,
    'governorate', o.governorate,
    'notes', o.notes,
    'gift_wrap', o.gift_wrap,
    'gift_message', o.gift_message,
    'preferred_delivery_date', o.preferred_delivery_date,
    'delivery_time_note', o.delivery_time_note,
    'created_at', o.created_at,
    'vendors', coalesce((
      select jsonb_agg(
        jsonb_build_object(
          'id', ov.id,
          'status', ov.status,
          'subtotal_minor', ov.subtotal_minor,
          'delivered_at', ov.delivered_at,
          'courier_name', ov.courier_name,
          'tracking_ref', ov.tracking_ref,
          'handed_over_at', ov.handed_over_at,
          'vendor_name', v.name,
          'vendor_slug', v.slug,
          'items', coalesce((
            select jsonb_agg(
              jsonb_build_object(
                'product_id', i.product_id,
                'product_name', i.product_name,
                'product_slug', i.product_slug,
                'unit_price_minor', i.unit_price_minor,
                'quantity', i.quantity,
                'line_total_minor', i.line_total_minor
              )
              order by i.created_at, i.id
            )
            from public.order_items i
            where i.order_vendor_id = ov.id
          ), '[]'::jsonb)
        )
        order by ov.created_at, ov.id
      )
      from public.order_vendors ov
      join public.vendors v on v.id = ov.vendor_id
      where ov.order_id = o.id
    ), '[]'::jsonb)
  )
  from public.orders o
  where o.id = p_order_id
    and o.guest_token_hash is not null
    and o.guest_token_hash = lower(p_token_hash)
    and p_token_hash ~ '^[0-9a-f]{64}$'
    and (o.guest_token_expires_at is null
         or o.guest_token_expires_at > now());
$$;

revoke all on function public.get_guest_order(uuid, text)
  from public, anon, authenticated;
grant execute on function public.get_guest_order(uuid, text)
  to service_role;
